import requests
import robot
from requests.structures import CaseInsensitiveDict
from robot.api.deco import keyword
from robot.libraries.BuiltIn import BuiltIn

from RequestsLibrary import log
from RequestsLibrary.compat import urljoin
from RequestsLibrary.multipart import create_multipart_encoder
from RequestsLibrary.utils import (
    is_list_or_tuple,
    is_file_descriptor,
    is_multipart_encoder,
    get_multipart_file_descriptors,
    warn_if_equal_symbol_in_url_session_less,
)


class RequestsKeywords(object):

    def __init__(self):
        self._cache = robot.utils.ConnectionCache("No sessions created")
        self.builtin = BuiltIn()
        self.debug = 0
        # The following variables are related to session but used in _common_request :(
        self.timeout = None
        self.cookies = None
        self.last_response = None

    def _common_request(self, method, session, uri, **kwargs):

        if session:
            request_function = getattr(session, "request")
        else:
            request_function = getattr(requests, "request")

        self._capture_output()

        data = kwargs.get("data")
        if is_multipart_encoder(data):
            # The boundary is generated by the encoder, an explicit Content-Type still wins
            headers = CaseInsensitiveDict(kwargs.get("headers") or {})
            headers.setdefault("Content-Type", data.content_type)
            kwargs["headers"] = headers

        resp = request_function(
            method,
            self._merge_url(session, uri),
            timeout=self._get_timeout(kwargs.pop("timeout", None)),
            cookies=kwargs.pop("cookies", self.cookies),
            **kwargs
        )

        log.log_request(resp)
        self._print_debug()

        log.log_response(resp)

        self.last_response = resp

        files = kwargs.get("files", {}) or {}
        data = kwargs.get("data", []) or []

        self._close_file_descriptors(files, data)

        return resp

    @staticmethod
    def _close_file_descriptors(files, data):
        """
        Helper method that closes any open file descriptors.
        """
        
        if is_list_or_tuple(files):
            files_descriptor_to_close = filter(
                is_file_descriptor, [file[1][1] for file in files] + [data]
            )
        else:
            files_descriptor_to_close = filter(
                is_file_descriptor, list(files.values()) + [data]
            )

        if is_multipart_encoder(data):
            files_descriptor_to_close = list(files_descriptor_to_close) + get_multipart_file_descriptors(data)

        for file_descriptor in files_descriptor_to_close:
            file_descriptor.close()
    
    @staticmethod
    def _merge_url(session, uri):
        """
        Helper method that join session url and request url.
        It relies on urljoin that handles quite good join urls and multiple /
        but has some counterintuitive behaviours if you join uri starting with /
        It handles also override in case a full url (http://etc) is passed as uri.
        """
        base = ""
        if session:
            base = session.url
        if session and uri and not session.url.endswith("/"):
            base = session.url + "/"
        if session and uri and uri.startswith("/"):
            uri = uri[1:]
        url = urljoin(base, uri)
        return url

    @keyword("Status Should Be")
    def status_should_be(self, expected_status, response=None, msg=None):
        """
        Fails if response status code is different than the expected.

        ``expected_status`` could be the code number as an integer or as string.
        But it could also be a named status code like 'ok', 'created', 'accepted' or
        'bad request', 'not found' etc.

        ``response`` is the output of other requests keywords like `GET` or `GET On Session`.
        If omitted the last response will be used.

        In case of failure an HTTPError will be automatically raised.
        A custom failure message ``msg`` can be added like in built-in keywords.

        New requests keywords like `GET` or `GET On Session` (starting from 0.8 version) already have an implicit assert
        mechanism that, by default, verifies the response status code.
        `Status Should Be` keyword can be useful when you disable implicit assert using ``expected_status=anything``.

        For example when you have a nested keyword that is used for both OK and ERROR responses:

        |   ***** Test Cases *****
        |
        |   Test Get Request And Make Sure Is A 404 Response
        |       ${resp}=            GET Custom Keyword That Returns OK or ERROR Response  case=notfound
        |       Status Should Be    404    ${resp}
        |       Should Be Equal As Strings  NOT FOUND  ${resp.reason}
        |
        |   Test Get Request And Make Sure Is OK
        |       ${resp}=            GET Custom Keyword That Returns OK or ERROR Response  case=pass
        |       Status Should Be    200    ${resp}
        |       Should Be Equal As Strings  OK  ${resp.reason}
        |
        |   ***** Keywords *****
        |
        |   GET Custom Keyword That Returns OK or ERROR Response
        |   [Arguments]  $case
        |        [...]
        |       IF $case == notfound
        |           $resp=     GET [...] expected_status=Anything
        |           [Return]   $resp
        |       ELSE
        |        [...]
        """
        if response is None:
            response = self.last_response
        self._check_status(expected_status, response, msg)

    @keyword("Request Should Be Successful")
    def request_should_be_successful(self, response=None):
        """
        Fails if response status code is a client or server error (4xx, 5xx).

        ``response`` is the output of other requests keywords like `GET On Session`.
        If omitted the last response will be used.

        In case of failure an HTTPError will be automatically raised.

        For a more versatile assert keyword see `Status Should Be`.
        """
        if not response:
            response = self.last_response
        self._check_status(None, response, msg=None)

    @staticmethod
    @keyword("Get File For Streaming Upload")
    def get_file_for_streaming_upload(path):
        """
        Opens and returns a file descriptor of a specified file to be passed as ``data`` parameter
        to other requests keywords.

        This allows streaming upload of large files without reading them into memory.

        File descriptor is binary mode and read only. Requests keywords will automatically close the file,
        if used outside this library it's up to the caller to close it.
        """
        return open(path, "rb")

    @staticmethod
    @keyword("Create Multipart Data")
    def create_multipart_data(fields=None, files=None, files_first=False):
        """
        Creates a ``multipart/form-data`` body, made of form ``fields`` and ``files``, the format used
        by HTML forms and by most APIs to upload files.

        The returned body is passed as ``data`` to `POST On Session`, `PUT On Session`, `PATCH On Session`
        or to the session-less `POST`, `PUT` and `PATCH` keywords. Files are streamed from disk while the
        request is sent instead of being read into memory, so it is suited for large uploads too.

        This keyword requires the ``requests-toolbelt`` package, it can be installed with
        ``pip install "robotframework-requests[multipart]"``.

        *Form fields*

        ``fields`` is a dictionary of ``name=value`` or a list of ``(name, value)`` pairs.
        A list allows to send the same field name several times.
        Values that are dictionaries or lists are sent as JSON strings, other values as strings.

        | ${settings}=    Create Dictionary    everything=${True}
        | ${fields}=      Create Dictionary    action=add    settings=${settings}
        | # sent as: action = add, settings = {"everything": true}
        |
        | ${tag_1}=       Create List    tag    one
        | ${tag_2}=       Create List    tag    two
        | ${fields}=      Create List    ${tag_1}    ${tag_2}
        | # sent as: tag = one, tag = two

        *Files*

        ``files`` is a dictionary of ``name=path``, or a list where each file is described with one of
        the following formats. A list allows to send several files with the same name.

        | = Format =                               | = Description =                                                     |
        | ``(name, path)``                         | File name and content type are taken from ``path``.                 |
        | ``(name, path, content_type)``           | With its own content type.                                          |
        | ``(name, path, content_type, filename)`` | With its own file name, ``content_type`` can be ``${None}``.        |
        | ``(name, [path, ...])``                  | Several files with the same name.                                   |
        | ``{name, path, content_type, filename}`` | A dictionary, ``content_type`` and ``filename`` keys are optional.  |

        | ${file_1}=    Create List    document    ${CURDIR}/report.pdf
        | ${file_2}=    Create List    document    ${CURDIR}/report    application/pdf
        | ${file_3}=    Create List    document    ${CURDIR}/r.pdf    ${None}    report.pdf
        | ${file_4}=    Create List    attachments    ${paths}
        | ${file_5}=    Create Dictionary    name=document    path=${CURDIR}/report.pdf
        | ${files}=     Create List    ${file_1}    ${file_4}

        In a dictionary of ``name=path``, the path can also be a list of paths: ``attachments=${paths}``.
        ``filename``, the file name given to the server, defaults to the base name of ``path``.
        ``content_type`` defaults to the type guessed from the file name extension,
        or ``application/octet-stream`` when it is unknown.

        *Order of the parts*

        Parts are sent in the given order, fields first and then files.
        Set ``files_first`` to ``${True}`` for servers that expect the files before the fields.

        *Sending the body*

        The ``Content-Type`` header, ``multipart/form-data`` with the generated boundary, is set
        automatically when the request is sent, unless a ``Content-Type`` is explicitly passed in the
        request ``headers``. Session headers, like an ``Authorization`` token, are sent as usual and
        a ``Content-Type`` set on the session is replaced for this request only.

        Files are opened by this keyword and closed by the requests keyword once the request is sent,
        so create a new body for each request. Within that request the body can be sent again from its
        start, so session retries and redirects resend it whole.

        *Examples*

        A file with form fields, on a session authenticated with a Bearer token:
        | ${headers}=      Create Dictionary    Authorization=Bearer ${token}
        | Create Session   api    https://example.com    headers=${headers}
        | ${settings}=     Create Dictionary    everything=${True}
        | ${fields}=       Create Dictionary    action=add    settings=${settings}
        | ${files}=        Create Dictionary    document=${CURDIR}/report.pdf
        | ${multipart}=    Create Multipart Data    fields=${fields}    files=${files}
        | ${resp}=         POST On Session    api    /upload    data=${multipart}

        Several files with the same name, a file with its own content type and file name,
        sent before the fields:
        | ${paths}=        Create List    ${CURDIR}/a.txt    ${CURDIR}/b.txt
        | ${attachments}=  Create List    attachments    ${paths}
        | ${metadata}=     Create List    metadata    ${CURDIR}/meta    application/xml    meta.xml
        | ${files}=        Create List    ${attachments}    ${metadata}
        | ${fields}=       Create Dictionary    action=add
        | ${multipart}=    Create Multipart Data    fields=${fields}    files=${files}    files_first=${True}
        | ${resp}=         PUT On Session    api    /upload    data=${multipart}
        """
        return create_multipart_encoder(fields, files, files_first)

    @keyword("Last response")
    def get_last_response(self) -> requests.Response:
        """
        Returns the response from the last request.
        """
        return self.last_response

    @keyword("GET")
    @warn_if_equal_symbol_in_url_session_less
    def session_less_get(
        self, url, params=None, expected_status=None, msg=None, **kwargs
    ):
        """
        Sends a GET request.

        The endpoint used to retrieve the resource is the ``url``, while query
        string parameters can be passed as string, dictionary (or list of tuples or bytes)
        through the ``params``.

        By default this keyword fails if a status code with error values is returned in the response,
        this behavior can be modified using the ``expected_status`` and ``msg`` parameters,
        read more about it in `Status Should Be` keyword documentation.
        In order to disable this implicit assert mechanism you can pass as ``expected_status`` the values ``any`` or
        ``anything``.

        Other optional requests arguments can be passed using ``**kwargs`` here is a list:

        | ``data``     | Dictionary, list of tuples, bytes, or file-like object to send in the body of the request. It can also be a multipart body created with `Create Multipart Data`. |
        | ``json``     | A JSON serializable Python object to send in the body of the request. |
        | ``headers``  | Dictionary of HTTP Headers to send with the request. |
        | ``cookies``  | Dict or CookieJar object to send with the request. |
        | ``files``    | Dictionary of file-like-objects (or ``{'name': file-tuple}``) for multipart encoding upload. ``file-tuple`` can be a 2-tuple ``('filename', fileobj)``, 3-tuple ``('filename', fileobj, 'content_type')`` or a 4-tuple ``('filename', fileobj, 'content_type', custom_headers)``, where ``'content-type'`` is a string defining the content type of the given file and ``custom_headers`` a dict-like object containing additional headers to add for the file. List or tuple of ``('key': file-tuple)`` allows uploading multiple files with the same key, resulting in a list of files on the receiving end. |
        | ``auth`` | Auth tuple to enable Basic/Digest/Custom HTTP Auth. |
        | ``timeout`` | How many seconds to wait for the server to send data before giving up, as a float, or a ``(connect timeout, read timeout)`` tuple. |
        | ``allow_redirects`` | Boolean. Enable/disable (values ``${True}`` or ``${False}``). Only for HEAD method keywords allow_redirection defaults to ``${False}``, all others ``${True}``. |
        | ``proxies`` | Dictionary mapping protocol or protocol and host to the URL of the proxy (e.g. {'http': 'foo.bar:3128', 'http://host.name': 'foo.bar:4012'}) |
        | ``verify``  | Either a boolean, in which case it controls whether we verify the server's TLS certificate, or a string, in which case it must be a path to a CA bundle to use. Defaults to ``${True}``. Warning: if a session has been created with ``verify=${False}`` any other requests will not verify the SSL certificate. |
        | ``stream`` | if ``${False}``, the response content will be immediately downloaded. |
        | ``cert`` | if String, path to ssl client cert file (.pem). If Tuple, ('cert', 'key') pair. |

        For more updated and complete information verify the official Requests api documentation:
        https://requests.readthedocs.io/en/latest/api/

        """
        response = self._common_request("GET", None, url, params=params, **kwargs)
        self._check_status(expected_status, response, msg)
        return response

